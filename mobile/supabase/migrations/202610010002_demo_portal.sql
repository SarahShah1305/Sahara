create or replace function public.book_demo_appointment(p_hospital_id text,p_specialty text,p_doctor_name text,p_appointment_at timestamptz,p_resource_type text default null) returns uuid language plpgsql security definer set search_path='' as $$ declare v_id uuid; begin if auth.uid() is null then raise exception 'Sign in required'; end if; if p_resource_type is not null then update public.hospital_resources set occupied=occupied+1,available=available-1,updated_at=now() where hospital_id=p_hospital_id and resource_type=p_resource_type and available>0; if not found then raise exception 'No reported demo capacity remains for this resource'; end if; end if; insert into public.sahara_appointments(user_id,hospital_id,specialty,doctor_name,appointment_at,resource_type,status,demo_only) values(auth.uid(),p_hospital_id,p_specialty,p_doctor_name,p_appointment_at,p_resource_type,'requested',true) returning id into v_id; return v_id; end; $$;

create or replace function public.mark_demo_appointment_accepted(p_appointment_id uuid) returns void language plpgsql security definer set search_path='' as $$ begin update public.sahara_appointments set status='demo_accepted' where id=p_appointment_id and user_id=auth.uid() and status='requested' and demo_only=true; if not found then raise exception 'Demo appointment could not be updated'; end if; end; $$;

