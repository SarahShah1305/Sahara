create or replace function public.adjust_demo_capacity(p_hospital_id text,p_resource_type text,p_delta integer) returns void language plpgsql security definer set search_path='' as $$ begin
  if auth.uid() is null then raise exception 'Sign in required'; end if;
  if p_delta not in (-1,1) then raise exception 'Demo adjustment must be -1 or 1'; end if;
  update public.hospital_resources set available=available+p_delta, occupied=occupied-p_delta, updated_at=now()
  where hospital_id=p_hospital_id and resource_type=p_resource_type and available+p_delta>=0 and occupied-p_delta>=0;
  if not found then raise exception 'Capacity is already at its demo limit'; end if;
end; $$;
revoke all on function public.adjust_demo_capacity(text,text,integer) from public;
grant execute on function public.adjust_demo_capacity(text,text,integer) to authenticated;
