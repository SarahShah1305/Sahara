create table if not exists public.sahara_hospitals (hospital_id text primary key, name text not null, area text, city text not null default 'Hyderabad', phone text, specialties text[] not null default '{}', demo_only boolean not null default true);

create table if not exists public.hospital_resources (hospital_id text not null references public.sahara_hospitals(hospital_id) on delete cascade, resource_type text not null, total integer not null default 0 check(total>=0), occupied integer not null default 0 check(occupied>=0), unavailable integer not null default 0 check(unavailable>=0), available integer not null default 0 check(available>=0), demo_only boolean not null default true, updated_at timestamptz not null default now(), primary key(hospital_id,resource_type), check(total>=occupied+unavailable+available));

create table if not exists public.sahara_doctors (id uuid primary key default gen_random_uuid(), hospital_id text not null references public.sahara_hospitals(hospital_id) on delete cascade, full_name text not null, specialty text not null, demo_only boolean not null default true, unique(hospital_id,specialty));

create table if not exists public.sahara_appointments (id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade, hospital_id text not null references public.sahara_hospitals(hospital_id), specialty text not null, doctor_name text not null, appointment_at timestamptz not null, resource_type text, status text not null default 'requested' check(status in ('requested','demo_accepted','cancelled')), demo_only boolean not null default true, created_at timestamptz not null default now());

create index if not exists sahara_appointments_user_idx on public.sahara_appointments(user_id,appointment_at desc);

create index if not exists sahara_appointments_hospital_idx on public.sahara_appointments(hospital_id,appointment_at);

alter table public.sahara_hospitals enable row level security; alter table public.hospital_resources enable row level security; alter table public.sahara_doctors enable row level security; alter table public.sahara_appointments enable row level security;

grant select on public.sahara_hospitals,public.hospital_resources,public.sahara_doctors to authenticated; grant select,insert on public.sahara_appointments to authenticated;

drop policy if exists "Signed-in demo users read hospitals" on public.sahara_hospitals; create policy "Signed-in demo users read hospitals" on public.sahara_hospitals for select to authenticated using(true);

drop policy if exists "Signed-in demo users read resources" on public.hospital_resources; create policy "Signed-in demo users read resources" on public.hospital_resources for select to authenticated using(true);

drop policy if exists "Signed-in demo users read doctors" on public.sahara_doctors; create policy "Signed-in demo users read doctors" on public.sahara_doctors for select to authenticated using(true);

drop policy if exists "Signed-in demo users read demo appointments" on public.sahara_appointments;
drop policy if exists "Users read own demo appointments" on public.sahara_appointments;
create policy "Users read own demo appointments" on public.sahara_appointments for select to authenticated using(user_id=auth.uid());

drop policy if exists "Patients create own demo appointments" on public.sahara_appointments; create policy "Patients create own demo appointments" on public.sahara_appointments for insert to authenticated with check(user_id=auth.uid() and demo_only=true and status='requested');

revoke update,delete on public.hospital_resources from anon,authenticated;

